#!/usr/bin/env node
/**
 * sync-browser-secrets.mjs — GENERATE `.env.playwright.local`, the `--secrets` file of every playwright-*
 * MCP server, from the test-user passwords in `.env.local` for the current TEST_ENV.
 *
 * Why: an agent that signs in through the real UI must never hold the password. With `--secrets`,
 * the agent types the NAME (`ADMIN_PASSWORD`) and Playwright MCP substitutes the value and masks it in
 * its output, so the password never enters the model's context or the transcript. gen-mcp passes the
 * file to every Playwright lane when it exists.
 *
 * - Names: ADMIN_PASSWORD and USER_PASSWORD always, plus every other `*_PASSWORD` the operator keeps in
 *   .env.local — bare, i.e. the `_<ENV>` suffix of the current env stripped. Never a token- or key-shaped
 *   name: least privilege is why this file is separate from .env.local.
 * - Values: the layered env for TEST_ENV (suffix-promoted). A name without a value is not written (an
 *   empty value would type '') and is listed.
 * - Prints names only, never a value. `--check` writes nothing and exits 1 when the file is stale.
 * The MCP servers read the file at START: after a change, reconnect playwright-* (or restart).
 *
 * This is option A. When the vc-secrets declaration keeps the passwords (option B, lib/passwords.mjs),
 * the lanes run from vc-secrets and no file is wanted: this script then writes nothing and says so.
 *
 * Usage: TEST_ENV=<env> node sync-browser-secrets.mjs [--check]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "dotenv";
import { loadLayeredEnv } from "../../scripts/lib/load-layered-env.mjs";
import { outputRoot } from "./lib/paths.mjs";
import { standDownIfHostGoverned } from "./lib/governance.mjs";
import { declaredPasswords } from "./lib/passwords.mjs";

export const SECRETS_FILE = ".env.playwright.local";
const ALWAYS = ["ADMIN_PASSWORD", "USER_PASSWORD"];
const TOKEN_SHAPED = /TOKEN|API|KEY|SECRET|PAT\b|_PAT_/;

/** dotenv-safe serialisation of one value; null when no quoting style carries it unchanged. */
function serialise(v) {
  if (/^[^\s#'"`\\]*$/.test(v)) return v;
  for (const q of ["'", "`", '"']) if (!v.includes(q) && !v.includes("\n") && !(q === '"' && v.includes("\\"))) return `${q}${v}${q}`;
  return null;
}

/** The bare password names for `env` from the parsed .env.local keys. Pure. */
export function passwordNames(localKeys, env) {
  const suffix = `_${String(env).toUpperCase()}`;
  const names = new Set(ALWAYS);
  for (const k of localKeys) {
    // ADMIN_PASSWORD_<THIS_ENV> → ADMIN_PASSWORD; another env's ADMIN_PASSWORD_<OTHER> does not end in
    // PASSWORD once nothing is stripped, so it is not this env's name.
    const bare = k.endsWith(suffix) ? k.slice(0, -suffix.length) : k;
    if (/PASSWORD$/.test(bare) && !TOKEN_SHAPED.test(bare)) names.add(bare);
  }
  return [...names].sort();
}

/** The file content for `env` from a { name: value } lookup. Pure. */
export function buildContent(env, names, valueOf) {
  const lines = [];
  const missing = [];
  const unserialisable = [];
  for (const n of names) {
    const v = valueOf(n) || "";
    if (!v) { missing.push(n); continue; }
    const s = serialise(v);
    if (s === null) { unserialisable.push(n); continue; }
    lines.push(`${n}=${s}`);
  }
  const header = [
    `# ${SECRETS_FILE} — GENERATED by /project-init (sync-browser-secrets.mjs). Do not edit: change .env.local and re-run.`,
    `# generated-for: TEST_ENV=${env}`,
    "# Login passwords only — never a token or key. The agent types the NAME; Playwright MCP types the value.",
    "# The playwright-* MCP servers read this at START: after a change, reconnect them (or restart Claude Code).",
    ...(missing.length ? [`# missing — no value in .env.local for this env: ${missing.join(", ")}`] : []),
  ];
  return { content: `${header.join("\n")}\n${lines.join("\n")}\n`, written: lines.map((l) => l.slice(0, l.indexOf("="))), missing, unserialisable };
}

/** What the file SHOULD hold now for the current TEST_ENV, and what it holds. Loads the layered env. */
export function currentState(root = outputRoot()) {
  const env = loadLayeredEnv();
  const localPath = join(root, ".env.local");
  const localKeys = existsSync(localPath) ? Object.keys(parse(readFileSync(localPath, "utf8"))) : [];
  const built = buildContent(env, passwordNames(localKeys, env), (n) => process.env[n]);
  const path = join(root, SECRETS_FILE);
  const before = existsSync(path) ? readFileSync(path, "utf8") : null;
  return { env, path, before, ...built, stale: before !== built.content };
}

function main() {
  standDownIfHostGoverned(outputRoot(), "sync-browser-secrets skipped: the browser lanes are the host's");
  const check = process.argv.includes("--check");
  let inVcSecrets = [];
  try {
    inVcSecrets = Object.keys(declaredPasswords(JSON.parse(readFileSync(join(outputRoot(), ".claude", "vc-secrets.local.json"), "utf8"))));
  } catch {
    /* no declaration — option A */
  }
  if (inVcSecrets.length) {
    console.log(`[browser-secrets] the passwords are in vc-secrets (${inVcSecrets.join(", ")}): the lanes run from there and need no ${SECRETS_FILE} — nothing written${existsSync(join(outputRoot(), SECRETS_FILE)) ? `; a leftover ${SECRETS_FILE} is deleted by migrate-secrets.mjs --strip` : ""}`);
    return;
  }
  const s = currentState();
  if (s.unserialisable.length) {
    console.error(`[browser-secrets] ✗ no dotenv quoting carries the value of ${s.unserialisable.join(", ")} — change that password`);
    process.exit(2);
  }
  console.log(`[browser-secrets] ${SECRETS_FILE} for TEST_ENV=${s.env}: ${s.written.join(", ") || "(no password set yet)"}`);
  for (const n of s.missing) console.log(`[browser-secrets] MISSING ${n} — no value in .env.local for this env; fill it, then re-run`);
  if (check) {
    console.log(s.stale ? `[browser-secrets] ✗ out of date — run sync-browser-secrets.mjs` : "[browser-secrets] ✓ up to date");
    process.exit(s.stale ? 1 : 0);
  }
  if (!s.stale) { console.log("[browser-secrets] ✓ already up to date — nothing written"); return; }
  writeFileSync(s.path, s.content, "utf8");
  console.log(`[browser-secrets] ✓ wrote ${SECRETS_FILE}. Restart Claude Code (or reconnect playwright-*) for the browser lanes to read it.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();

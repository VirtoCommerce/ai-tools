#!/usr/bin/env node
// scripts/seed-data/b2b/wave-personas.mjs — the per-wave persona clones (test-data/personas/sets.json).
//
//   npm run td:validate:wave-personas   # the committed clones match what the originals derive (exit 1 on drift; CI)
//   npm run td:gen:wave-personas        # (re)write the clone rows + aliases from the originals
//
// A clone of persona P for set S is DERIVED from P's own alias and CSV row: the same org, role, store and password
// token, its own id and login. Never edit a clone by hand: change the original, then --write. The clones are created
// on a stand by the persona's own seeder (`npm run seed:users` for personal, `npm run seed:company-users -- b2b --only
// agent-test-wave-` for B2B), which records each login in test-accounts.local.json; their passwords are the
// originals' tokens, so a browser lane types the same password NAME.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse } from 'csv-parse/sync';
import { stringify } from 'csv-stringify/sync';
import { cloneAlias, loadPersonaSets } from '../../lib/persona-sets.mjs';

const ROOT = process.cwd();
const ALIASES = 'test-data/aliases.json';
const write = process.argv.includes('--write');
const defs = loadPersonaSets(ROOT);

// Where each persona's row lives and how its clone ids are numbered (USER-90k, USR-9pk, CON-9pk).
const SOURCES = {
  'users/test-users': { file: 'test-data/users/test-users.csv', id: 'user_id', prefix: 'USER-' },
  'b2b/users': { file: 'test-data/b2b/users.csv', id: 'user_id', prefix: 'USR-', contacts: 'test-data/b2b/contacts.csv' },
};
export const cloneEmail = (alias, set) => `agent-test-wave-${set.toLowerCase()}-${alias.toLowerCase().replace(/_/g, '-')}@test-agent.com`;

const readCsv = (f) => { const t = readFileSync(join(ROOT, f), 'utf8'); return { text: t, rows: parse(t, { columns: true, skip_empty_lines: true, bom: true }), header: parse(t, { to_line: 1, bom: true })[0] }; };
const csvLine = (header, row) => stringify([header.map((h) => row[h] ?? '')]).replace(/\r?\n$/, '');

/** Every clone row + alias the sets derive. Pure: reads the originals, writes nothing. */
export function deriveClones(aliases, csv) {
  const out = { rows: {}, contacts: [], aliases: {} };
  const b2bIdx = new Map(defs.personas.filter((p) => aliases[p]?.file === 'b2b/users').map((p, i) => [p, i + 1]));
  for (const p of defs.personas) {
    const a = aliases[p];
    const src = SOURCES[a?.file];
    if (!src || !a.filter?.user_id) throw new Error(`${p}: only CSV-backed personas filtered by user_id can be cloned (alias file ${a?.file ?? 'missing'})`);
    const orig = csv[src.file].rows.find((r) => r[src.id] === a.filter.user_id);
    if (!orig) throw new Error(`${p}: ${src.file} has no ${src.id} ${a.filter.user_id}`);
    defs.sets.forEach((set, k) => {
      const n = src.prefix === 'USER-' ? `90${k + 1}` : `9${b2bIdx.get(p)}${k + 1}`;
      const id = `${src.prefix}${n}`, email = cloneEmail(p, set), note = `Wave persona set ${set}: clone of ${p} (${a.filter.user_id}) — generated by td:gen:wave-personas`;
      const row = { ...orig, [src.id]: id, email };
      if (src.prefix === 'USER-') Object.assign(row, { last_name: `${orig.last_name} ${set}`, test_purpose: note, notes: '', seeded: 'true' });
      else {
        const con = csv[src.contacts].rows.find((r) => r.contact_id === orig.contact_id);
        if (!con) throw new Error(`${p}: contacts.csv has no ${orig.contact_id}`);
        const cid = `CON-${n}`;
        Object.assign(row, { platform_id: '', contact_id: cid, user_name: email, test_purpose: note, seeded: 'true', alias: cloneAlias(p, set) });
        out.contacts.push({ ...con, contact_id: cid, platform_id: '', email, last_name: `${con.last_name} ${set}`, full_name: `${con.full_name} ${set}`, test_purpose: note, seeded: 'true' });
      }
      (out.rows[src.file] ??= []).push(row);
      out.aliases[cloneAlias(p, set)] = { ...structuredClone(a), filter: { ...a.filter, user_id: id }, notes: note };
    });
  }
  return out;
}

// --- text surgery on aliases.json: it does not round-trip through JSON.stringify, so clones are spliced in as text ---
function removeKey(text, key) {
  const m = new RegExp(`,(\\r?\\n)  "${key}": `).exec(text);
  if (!m) return text;
  let i = m.index + m[0].length, depth = 0, inStr = false;
  for (; i < text.length; i++) {
    const c = text[i];
    if (inStr) { if (c === '\\') i++; else if (c === '"') inStr = false; continue; }
    if (c === '"') inStr = true;
    else if (c === '{' || c === '[') depth++;
    else if (c === '}' || c === ']') { depth--; if (depth === 0) { i++; break; } }
  }
  return text.slice(0, m.index) + text.slice(i);
}
function appendKeys(text, entries) {
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const end = text.lastIndexOf('}');
  const body = Object.entries(entries).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v, null, 2).replace(/\n/g, `${eol}  `)}`).join(`,${eol}`);
  return `${text.slice(0, end).replace(/\s*$/, '')},${eol}${body}${eol}}${eol}`;
}

const aliasText = readFileSync(join(ROOT, ALIASES), 'utf8');
const aliases = JSON.parse(aliasText);
const files = [...new Set(Object.values(SOURCES).flatMap((s) => [s.file, s.contacts].filter(Boolean)))];
const csv = Object.fromEntries(files.map((f) => [f, readCsv(f)]));
const isClone = (id, prefix) => id?.startsWith(`${prefix}9`) && id.length === prefix.length + 3;
const want = deriveClones(aliases, csv);

const drift = [];
for (const [k, v] of Object.entries(want.aliases)) if (JSON.stringify(aliases[k]) !== JSON.stringify(v)) drift.push(`alias ${k}`);
for (const f of files) {
  const src = Object.values(SOURCES).find((s) => s.file === f), idCol = src ? src.id : 'contact_id', prefix = src ? src.prefix : 'CON-';
  const have = csv[f].rows.filter((r) => isClone(r[idCol], prefix)).map((r) => csvLine(csv[f].header, r));
  const need = (src ? want.rows[f] ?? [] : want.contacts).map((r) => csvLine(csv[f].header, r));
  if (JSON.stringify(have) !== JSON.stringify(need)) drift.push(`${f} (${have.length} clone rows, ${need.length} derived)`);
}

if (!write) {
  if (drift.length) { console.error(`td:gen:wave-personas: clones out of date — ${drift.join('; ')}. Run: npm run td:gen:wave-personas`); process.exit(1); }
  console.log(`td:gen:wave-personas: ${Object.keys(want.aliases).length} clone(s) of ${defs.personas.length} persona(s) × ${defs.sets.length} set(s) match their originals`);
  process.exit(0);
}

let at = aliasText;
for (const k of Object.keys(aliases)) if (defs.sets.some((s) => defs.personas.some((p) => k === cloneAlias(p, s)))) at = removeKey(at, k);
at = appendKeys(at, want.aliases);
JSON.parse(at); // refuse to write a broken file
writeFileSync(join(ROOT, ALIASES), at);
for (const f of files) {
  const src = Object.values(SOURCES).find((s) => s.file === f), idCol = src ? src.id : 'contact_id', prefix = src ? src.prefix : 'CON-';
  const eol = csv[f].text.includes('\r\n') ? '\r\n' : '\n';
  // Clone rows are single-line rows this script wrote; every other line (multi-line cells included) stays as it is.
  const cloneLine = new RegExp(`^"?${prefix}9\\d\\d"?,`);
  const kept = csv[f].text.replace(/(\r?\n)+$/, '').split(eol).filter((line) => !cloneLine.test(line));
  const add = (src ? want.rows[f] ?? [] : want.contacts).map((r) => csvLine(csv[f].header, r));
  const text = [...kept, ...add].join(eol) + eol;
  if (parse(text, { columns: true, skip_empty_lines: true, bom: true }).length !== csv[f].rows.filter((r) => !isClone(r[idCol], prefix)).length + add.length) throw new Error(`${f}: row count check failed`);
  writeFileSync(join(ROOT, f), text);
}
console.log(`td:gen:wave-personas: wrote ${Object.keys(want.aliases).length} clone alias(es) and their rows`);
